package com.bahikhata.app.util

import android.content.Context
import android.graphics.Color as AColor
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.bahikhata.app.data.Entry
import com.bahikhata.app.data.Invoice
import com.bahikhata.app.data.Party
import java.io.File
import com.bahikhata.app.util.S
import java.io.FileOutputStream

object Pdf {

    /** PDF colour theme (Settings → Bill & PDF): (main, accent). */
    private fun themeColors(): Pair<Int, Int> = when (S.pdfTheme) {
        "blue" -> AColor.parseColor("#0B2A4A") to AColor.parseColor("#2F80ED")
        "green" -> AColor.parseColor("#0F3D2E") to AColor.parseColor("#2BAE66")
        "maroon" -> AColor.parseColor("#4A0E1C") to AColor.parseColor("#C08A3E")
        "black" -> AColor.parseColor("#111111") to AColor.parseColor("#8A8A8A")
        else -> AColor.parseColor("#14213D") to AColor.parseColor("#C9A227")
    }
    private fun signatoryLabel() = S.pdfSignatory.ifEmpty { "Authorised Signatory" }
    private fun footerLine() = S.pdfFooter.ifEmpty { "Thank you for your business!" }
    private fun upiLine(): String? = S.upiId.takeIf { S.pdfUpi && it.isNotEmpty() }?.let { "UPI $it" }

    private const val PAGE_W = 595
    private const val PAGE_H = 842
    private const val MARGIN = 40f

    private fun paint(size: Float, bold: Boolean = false, color: Int = AColor.BLACK): Paint {
        val p = Paint()
        p.isAntiAlias = true
        p.textSize = size
        p.color = color
        p.typeface = if (bold) Typeface.create(Typeface.DEFAULT, Typeface.BOLD) else Typeface.DEFAULT
        return p
    }

    private fun line(canvas: android.graphics.Canvas, y: Float, paint: Paint) {
        canvas.drawLine(MARGIN, y, PAGE_W - MARGIN, y, paint)
    }

    /** Party ledger / statement of account — premium navy + gold design. */
    fun statement(
        ctx: Context,
        party: Party,
        entries: List<Entry>,
        shopName: String,
        shopPhone: String
    ): File {
        val (navy, gold) = themeColors()
        val soft = AColor.parseColor("#F7F3E8")
        val grayText = AColor.parseColor("#6B6B6B")
        val red = AColor.parseColor("#D7263D")
        val green = AColor.parseColor("#1E8E3E")
        val serifB = Typeface.create(Typeface.SERIF, Typeface.BOLD)
        fun p(size: Float, color: Int = AColor.BLACK, bold: Boolean = false, serif: Boolean = false, align: Paint.Align = Paint.Align.LEFT) =
            Paint().apply {
                isAntiAlias = true; textSize = size; this.color = color; textAlign = align
                typeface = if (serif) (if (bold) serifB else Typeface.SERIF) else if (bold) Typeface.create(Typeface.DEFAULT, Typeface.BOLD) else Typeface.DEFAULT
            }
        val fill = Paint().apply { isAntiAlias = true; style = Paint.Style.FILL }
        val goldRule = Paint().apply { color = gold; strokeWidth = 1f }
        val address = com.bahikhata.app.data.Repo.setting("address", "")
        val gstin = com.bahikhata.app.data.Repo.setting("gstin", "")
        val termsOn = com.bahikhata.app.data.Repo.setting("terms_on", "1") == "1"
        val terms = com.bahikhata.app.data.Repo.setting("terms", "").trim()
        val firstDate = entries.minOfOrNull { it.date }
        val lastDate = entries.maxOfOrNull { it.date } ?: System.currentTimeMillis()

        val doc = PdfDocument()
        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNo).create())
        var canvas = page.canvas
        val L = MARGIN
        val Rt = PAGE_W - MARGIN

        fun footer() {
            canvas.drawLine(L, PAGE_H - 40f, Rt, PAGE_H - 40f, goldRule)
            canvas.drawText("$shopName  ·  Generated by BahiKhata Pro  ·  ${fmtDate(System.currentTimeMillis())}", L, PAGE_H - 26f, p(8f, grayText))
            canvas.drawText("Page $pageNo", Rt, PAGE_H - 26f, p(8f, grayText, align = Paint.Align.RIGHT))
        }

        // ---- header band
        fill.color = navy
        canvas.drawRect(0f, 0f, PAGE_W.toFloat(), 118f, fill)
        canvas.drawLine(0f, 118f, PAGE_W.toFloat(), 118f, Paint().apply { color = gold; strokeWidth = 3f })
        canvas.drawText(shopName, L, 52f, p(26f, AColor.WHITE, bold = true, serif = true))
        var hy = 70f
        val caps = p(8.5f, gold).apply { letterSpacing = 0.12f }
        if (address.isNotBlank()) { canvas.drawText(address.uppercase(), L, hy, caps); hy += 12f }
        val contact = listOfNotNull(shopPhone.takeIf { it.isNotBlank() }?.let { "PH $it" }, gstin.takeIf { it.isNotBlank() }?.let { "GSTIN $it" }, upiLine()).joinToString("   ·   ")
        if (contact.isNotBlank()) { canvas.drawText(contact.uppercase(), L, hy, caps) }
        canvas.drawText("STATEMENT OF ACCOUNT", Rt, 50f, p(11f, gold, bold = true, align = Paint.Align.RIGHT).apply { letterSpacing = 0.15f })
        canvas.drawText((firstDate?.let { fmtDate(it) + "  –  " } ?: "") + fmtDate(lastDate), Rt, 66f, p(9f, AColor.WHITE, align = Paint.Align.RIGHT))

        // ---- party profile card
        var y = 140f
        val cardTop = y
        fill.color = soft
        canvas.drawRoundRect(android.graphics.RectF(L, cardTop, Rt, cardTop + 96f), 10f, 10f, fill)
        canvas.drawRoundRect(android.graphics.RectF(L, cardTop, Rt, cardTop + 96f), 10f, 10f, Paint().apply { color = gold; style = Paint.Style.STROKE; strokeWidth = 0.8f; isAntiAlias = true })
        val cx = L + 52f; val cy = cardTop + 48f; val rad = 32f
        val photo = if (S.pdfPhoto) PartyPhotos.load(ctx, party.id) else null
        if (photo != null) {
            val shader = android.graphics.BitmapShader(photo, android.graphics.Shader.TileMode.CLAMP, android.graphics.Shader.TileMode.CLAMP)
            val side = minOf(photo.width, photo.height).toFloat()
            val m = android.graphics.Matrix()
            val sc = (rad * 2) / side
            m.setScale(sc, sc)
            m.postTranslate(cx - rad - (photo.width - side) / 2f * sc, cy - rad - (photo.height - side) / 2f * sc)
            shader.setLocalMatrix(m)
            canvas.drawCircle(cx, cy, rad, Paint().apply { isAntiAlias = true; this.shader = shader })
        } else {
            fill.color = gold
            canvas.drawCircle(cx, cy, rad, fill)
            val ini = party.name.trim().split(" ").filter { it.isNotBlank() }.take(2).joinToString("") { it.take(1).uppercase() }.ifEmpty { "?" }
            canvas.drawText(ini, cx, cy + 8f, p(22f, AColor.WHITE, bold = true, serif = true, align = Paint.Align.CENTER))
        }
        canvas.drawCircle(cx, cy, rad + 2f, Paint().apply { color = gold; style = Paint.Style.STROKE; strokeWidth = 1.5f; isAntiAlias = true })
        val tx = cx + rad + 18f
        canvas.drawText(party.name, tx, cardTop + 36f, p(16f, navy, bold = true, serif = true))
        var py = cardTop + 52f
        if (party.phone.isNotBlank()) { canvas.drawText("Phone: ${party.phone}", tx, py, p(9.5f, grayText)); py += 13f }
        canvas.drawText((if (party.type == "SUPPLIER") "Supplier" else "Customer") + (if (party.note.isNotBlank()) "  ·  ${party.note.take(40)}" else ""), tx, py, p(9.5f, grayText))

        var closing = party.opening
        entries.forEach { closing += if (it.gave) it.amount else -it.amount }
        val balColor = if (closing > 0.005) red else if (closing < -0.005) green else grayText
        val bx = Rt - 150f
        fill.color = AColor.WHITE
        canvas.drawRoundRect(android.graphics.RectF(bx, cardTop + 14f, Rt - 12f, cardTop + 82f), 8f, 8f, fill)
        canvas.drawRoundRect(android.graphics.RectF(bx, cardTop + 14f, Rt - 12f, cardTop + 82f), 8f, 8f, Paint().apply { color = balColor; style = Paint.Style.STROKE; strokeWidth = 1.2f; isAntiAlias = true })
        val bc = (bx + Rt - 12f) / 2f
        canvas.drawText(if (closing > 0.005) "LENA HAI" else if (closing < -0.005) "DENA HAI" else "BARABAR", bc, cardTop + 32f, p(8.5f, balColor, bold = true, align = Paint.Align.CENTER).apply { letterSpacing = 0.12f })
        canvas.drawText(rupees(kotlin.math.abs(closing)), bc, cardTop + 60f, p(18f, balColor, bold = true, align = Paint.Align.CENTER))
        canvas.drawText("Total due", bc, cardTop + 74f, p(8f, grayText, align = Paint.Align.CENTER))

        // ---- table
        y = cardTop + 120f
        val cDate = L + 8f; val cDet = L + 82f; val cGave = L + 300f; val cGot = L + 380f; val cBal = Rt - 8f
        fun tableHead() {
            fill.color = navy
            canvas.drawRect(L, y - 13f, Rt, y + 7f, fill)
            val h = p(9f, gold, bold = true).apply { letterSpacing = 0.08f }
            canvas.drawText("DATE", cDate, y, h); canvas.drawText("DETAILS", cDet, y, h)
            canvas.drawText("DIYE", cGave + 60f, y, p(9f, gold, bold = true, align = Paint.Align.RIGHT))
            canvas.drawText("MILE", cGot + 60f, y, p(9f, gold, bold = true, align = Paint.Align.RIGHT))
            canvas.drawText("BALANCE", cBal, y, p(9f, gold, bold = true, align = Paint.Align.RIGHT))
            y += 22f
        }
        tableHead()
        val body = p(9.5f)
        var running = party.opening
        var row = 0
        var totGave = 0.0; var totGot = 0.0
        fun rowBg() {
            if (row % 2 == 1) { fill.color = soft; canvas.drawRect(L, y - 12f, Rt, y + 6f, fill) }
            row++
        }
        if (party.opening != 0.0) {
            rowBg()
            canvas.drawText("—", cDate, y, body)
            canvas.drawText("Opening balance", cDet, y, body)
            canvas.drawText(money(running), cBal, y, p(9.5f, align = Paint.Align.RIGHT))
            y += 18f
        }
        for (e in entries) {
            if (y > PAGE_H - 70f) {
                footer(); doc.finishPage(page); pageNo++
                page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNo).create())
                canvas = page.canvas
                y = MARGIN + 20f
                canvas.drawText("$shopName — ${party.name} (contd.)", L, y, p(11f, navy, bold = true, serif = true))
                y += 26f
                tableHead()
            }
            running += if (e.gave) e.amount else -e.amount
            if (e.gave) totGave += e.amount else totGot += e.amount
            rowBg()
            canvas.drawText(fmtDate(e.date), cDate, y, body)
            val det = (e.note.ifBlank { if (e.gave) "Diye (You Gave)" else "Mile (You Got)" }) + " · " + e.mode
            canvas.drawText(if (det.length > 40) det.take(39) + "…" else det, cDet, y, body)
            if (e.gave) canvas.drawText(money(e.amount), cGave + 60f, y, p(9.5f, red, align = Paint.Align.RIGHT))
            else canvas.drawText(money(e.amount), cGot + 60f, y, p(9.5f, green, align = Paint.Align.RIGHT))
            canvas.drawText(money(running), cBal, y, p(9.5f, align = Paint.Align.RIGHT))
            y += 18f
        }
        // summary row
        canvas.drawLine(L, y - 8f, Rt, y - 8f, goldRule)
        y += 8f
        canvas.drawText("TOTAL", cDet, y, p(10f, navy, bold = true))
        canvas.drawText(money(totGave), cGave + 60f, y, p(10f, red, bold = true, align = Paint.Align.RIGHT))
        canvas.drawText(money(totGot), cGot + 60f, y, p(10f, green, bold = true, align = Paint.Align.RIGHT))
        canvas.drawText(money(running), cBal, y, p(10f, navy, bold = true, align = Paint.Align.RIGHT))
        y += 8f
        canvas.drawLine(L, y, Rt, y, goldRule)
        y += 26f

        // terms
        if (termsOn && terms.isNotEmpty()) {
            val tp = p(9f, grayText)
            val lines = mutableListOf<String>()
            terms.lines().forEach { para ->
                var cur = ""
                para.split(" ").forEach { w ->
                    val t = if (cur.isEmpty()) w else "$cur $w"
                    if (tp.measureText(t) > (Rt - L - 10f)) { lines.add(cur); cur = w } else cur = t
                }
                lines.add(cur)
            }
            if (y + 30f + lines.size * 12f > PAGE_H - 110f) {
                footer(); doc.finishPage(page); pageNo++
                page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNo).create())
                canvas = page.canvas; y = MARGIN + 20f
            }
            canvas.drawText("TERMS & RULES", L, y, p(9.5f, gold, bold = true).apply { letterSpacing = 0.12f })
            y += 14f
            lines.forEach { canvas.drawText(it, L, y, tp); y += 12f }
            y += 10f
        }
        // signature
        val sy = maxOf(y + 40f, PAGE_H - 100f).coerceAtMost(PAGE_H - 52f)
        canvas.drawLine(Rt - 170f, sy, Rt, sy, Paint().apply { color = navy; strokeWidth = 0.8f })
        canvas.drawText(signatoryLabel(), Rt - 85f, sy + 13f, p(9f, navy, align = Paint.Align.CENTER))
        canvas.drawText("for $shopName", Rt - 85f, sy + 25f, p(8f, grayText, align = Paint.Align.CENTER))
        footer()
        doc.finishPage(page)

        val file = File(ctx.cacheDir, "statement_${party.id}_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return file
    }

    /** Business report for a date range: summary, top baaki, overdue, khata + cash entries. */
    fun report(ctx: Context, periodLabel: String, start: Long, end: Long): File {
        val (navy, gold) = themeColors()
        val soft = AColor.parseColor("#F7F3E8")
        val grayText = AColor.parseColor("#6B6B6B")
        val red = AColor.parseColor("#D7263D")
        val green = AColor.parseColor("#1E8E3E")
        val serifB = Typeface.create(Typeface.SERIF, Typeface.BOLD)
        fun p(size: Float, color: Int = AColor.BLACK, bold: Boolean = false, serif: Boolean = false, align: Paint.Align = Paint.Align.LEFT) =
            Paint().apply {
                isAntiAlias = true; textSize = size; this.color = color; textAlign = align
                typeface = if (serif) (if (bold) serifB else Typeface.SERIF) else if (bold) Typeface.create(Typeface.DEFAULT, Typeface.BOLD) else Typeface.DEFAULT
            }
        val R = com.bahikhata.app.data.Repo
        val shopName = R.businessName()
        val entries = R.entriesBetween(start, end).sortedBy { it.date }
        val cash = R.cashList().filter { it.date >= start && it.date < end }.sortedBy { it.date }
        val bills = R.invoices().filter { it.date >= start && it.date < end }
        val parties = R.parties()
        val gave = entries.filter { it.gave }.sumOf { it.amount }
        val got = entries.filter { !it.gave }.sumOf { it.amount }
        val cIn = cash.filter { it.cashIn }.sumOf { it.amount }
        val cOut = cash.filter { !it.cashIn }.sumOf { it.amount }
        val receivable = parties.filter { it.balance > 0 }.sumOf { it.balance }
        val payable = parties.filter { it.balance < 0 }.sumOf { -it.balance }
        val overdue = R.overdueSince()
        val fill = Paint().apply { isAntiAlias = true; style = Paint.Style.FILL }
        val goldRule = Paint().apply { color = gold; strokeWidth = 1f }
        val hair = Paint().apply { color = AColor.parseColor("#E5E5EA"); strokeWidth = 0.6f }

        val doc = PdfDocument()
        var pageNo = 1
        var page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNo).create())
        var canvas = page.canvas
        val L = MARGIN
        val Rt = PAGE_W - MARGIN
        var y = 0f

        fun footer() {
            canvas.drawLine(L, PAGE_H - 40f, Rt, PAGE_H - 40f, goldRule)
            canvas.drawText("$shopName  ·  Business Report  ·  Generated by BahiKhata Pro  ·  ${fmtDate(System.currentTimeMillis())}", L, PAGE_H - 26f, p(8f, grayText))
            canvas.drawText("Page $pageNo", Rt, PAGE_H - 26f, p(8f, grayText, align = Paint.Align.RIGHT))
        }
        fun newPage() {
            footer(); doc.finishPage(page); pageNo++
            page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, pageNo).create())
            canvas = page.canvas; y = MARGIN + 10f
        }
        fun need(h: Float) { if (y + h > PAGE_H - 60f) newPage() }
        fun heading(t: String) {
            need(40f)
            y += 8f
            canvas.drawText(t.uppercase(), L, y, p(10f, navy, bold = true).apply { letterSpacing = 0.12f })
            y += 5f
            canvas.drawLine(L, y, L + 40f, y, Paint().apply { color = gold; strokeWidth = 2f })
            y += 14f
        }
        fun cut(s: String, max: Float, paint: Paint): String {
            if (paint.measureText(s) <= max) return s
            var t = s
            while (t.isNotEmpty() && paint.measureText("$t…") > max) t = t.dropLast(1)
            return "$t…"
        }

        // header band
        fill.color = navy
        canvas.drawRect(0f, 0f, PAGE_W.toFloat(), 104f, fill)
        canvas.drawLine(0f, 104f, PAGE_W.toFloat(), 104f, Paint().apply { color = gold; strokeWidth = 3f })
        canvas.drawText(cut(shopName, 300f, p(24f, bold = true, serif = true)), L, 50f, p(24f, AColor.WHITE, bold = true, serif = true))
        canvas.drawText("BUSINESS REPORT", Rt, 46f, p(11f, gold, bold = true, align = Paint.Align.RIGHT).apply { letterSpacing = 0.15f })
        canvas.drawText(periodLabel + "   (" + fmtDate(start) + " – " + fmtDate(end - 1) + ")", Rt, 64f, p(9f, AColor.WHITE, align = Paint.Align.RIGHT))
        canvas.drawText(upiLine()?.uppercase() ?: "", L, 72f, p(8.5f, gold).apply { letterSpacing = 0.12f })
        y = 132f

        // summary tiles: 3 x 2
        val tiles = listOf(
            Triple("DIYE (GAVE)", rupees(gave), red), Triple("MILE (GOT)", rupees(got), green), Triple("NET KHATA", rupees(gave - got), navy),
            Triple("CASH AAYA", rupees(cIn), green), Triple("CASH GAYA", rupees(cOut), red), Triple("BIKRI (${bills.size} BILLS)", rupees(bills.sumOf { it.total }), navy)
        )
        val tw = (Rt - L - 20f) / 3f
        tiles.forEachIndexed { i, t ->
            val col = i % 3; val row = i / 3
            val x = L + col * (tw + 10f); val ty = y + row * 58f
            fill.color = soft
            canvas.drawRoundRect(x, ty, x + tw, ty + 48f, 8f, 8f, fill)
            canvas.drawText(t.first, x + 10f, ty + 17f, p(7.5f, grayText, bold = true).apply { letterSpacing = 0.1f })
            canvas.drawText(t.second, x + 10f, ty + 37f, p(14f, t.third, bold = true))
        }
        y += 58f * 2 + 6f
        val rate = if (gave > 0) "${(got / gave * 100).toInt()}%" else "—"
        canvas.drawText("Kul lena (abhi tak): ${rupees(receivable)}     Kul dena: ${rupees(payable)}     Vasooli rate: $rate", L, y, p(9.5f, navy, bold = true))
        y += 16f

        // top baaki
        val top = parties.filter { it.balance > 0 }.sortedByDescending { it.balance }.take(10)
        if (top.isNotEmpty()) {
            heading("Sabse zyada baaki")
            top.forEachIndexed { i, pt ->
                need(18f)
                if (i % 2 == 0) { fill.color = soft; canvas.drawRect(L, y - 11f, Rt, y + 5f, fill) }
                canvas.drawText("${i + 1}.  " + cut(pt.name, 260f, p(9.5f)), L + 6f, y, p(9.5f))
                val od = overdue[pt.id]
                if (od != null) canvas.drawText("Due nikal gayi (${((System.currentTimeMillis() - od) / 86_400_000L)} din)", L + 300f, y, p(8f, red))
                canvas.drawText(rupees(pt.balance), Rt - 6f, y, p(9.5f, red, bold = true, align = Paint.Align.RIGHT))
                y += 16f
            }
        }

        // khata entries
        heading("Khata entries (${entries.size})")
        if (entries.isEmpty()) { canvas.drawText("Is samay me koi entry nahi.", L, y, p(9f, grayText)); y += 14f }
        else {
            fun head() {
                fill.color = navy; canvas.drawRect(L, y - 11f, Rt, y + 5f, fill)
                val hp = p(8f, AColor.WHITE, bold = true)
                canvas.drawText("DATE", L + 6f, y, hp); canvas.drawText("PARTY", L + 80f, y, hp); canvas.drawText("MODE", L + 300f, y, hp)
                canvas.drawText("DIYE", Rt - 90f, y, hp.apply { textAlign = Paint.Align.RIGHT })
                canvas.drawText("MILE", Rt - 6f, y, hp)
                y += 18f
            }
            head()
            entries.forEachIndexed { i, e ->
                if (y + 16f > PAGE_H - 60f) { newPage(); head() }
                if (i % 2 == 1) { fill.color = soft; canvas.drawRect(L, y - 11f, Rt, y + 5f, fill) }
                canvas.drawText(fmtDate(e.date), L + 6f, y, p(8.5f, grayText))
                canvas.drawText(cut(e.partyName + (if (e.note.isNotBlank()) " · " + e.note else ""), 210f, p(8.5f)), L + 80f, y, p(8.5f))
                canvas.drawText(e.mode, L + 300f, y, p(8f, grayText))
                if (e.gave) canvas.drawText(rupees(e.amount), Rt - 90f, y, p(8.5f, red, bold = true, align = Paint.Align.RIGHT))
                else canvas.drawText(rupees(e.amount), Rt - 6f, y, p(8.5f, green, bold = true, align = Paint.Align.RIGHT))
                y += 16f
            }
            need(20f)
            canvas.drawLine(L, y - 8f, Rt, y - 8f, hair)
            canvas.drawText("Total", L + 6f, y + 4f, p(9f, navy, bold = true))
            canvas.drawText(rupees(gave), Rt - 90f, y + 4f, p(9f, red, bold = true, align = Paint.Align.RIGHT))
            canvas.drawText(rupees(got), Rt - 6f, y + 4f, p(9f, green, bold = true, align = Paint.Align.RIGHT))
            y += 20f
        }

        // cashbook
        if (cash.isNotEmpty()) {
            heading("Cashbook (${cash.size})")
            cash.forEachIndexed { i, c ->
                need(16f)
                if (i % 2 == 1) { fill.color = soft; canvas.drawRect(L, y - 11f, Rt, y + 5f, fill) }
                canvas.drawText(fmtDate(c.date), L + 6f, y, p(8.5f, grayText))
                canvas.drawText(cut(c.category + (if (c.note.isNotBlank()) " · " + c.note else ""), 210f, p(8.5f)), L + 80f, y, p(8.5f))
                canvas.drawText(c.mode, L + 300f, y, p(8f, grayText))
                if (c.cashIn) canvas.drawText(rupees(c.amount), Rt - 6f, y, p(8.5f, green, bold = true, align = Paint.Align.RIGHT))
                else canvas.drawText(rupees(c.amount), Rt - 90f, y, p(8.5f, red, bold = true, align = Paint.Align.RIGHT))
                y += 16f
            }
            need(20f)
            canvas.drawText("Aaya ${rupees(cIn)}   ·   Gaya ${rupees(cOut)}   ·   Bacha ${rupees(cIn - cOut)}", L + 6f, y + 4f, p(9f, navy, bold = true))
            y += 20f
        }

        footer()
        doc.finishPage(page)
        val file = File(ctx.cacheDir, "report_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return file
    }

    /** GST / retail invoice. */
    fun invoice(
        ctx: Context,
        inv: Invoice,
        shopName: String,
        shopAddress: String,
        shopPhone: String,
        shopGstin: String
    ): File {
        val doc = PdfDocument()
        val page = doc.startPage(PdfDocument.PageInfo.Builder(PAGE_W, PAGE_H, 1).create())
        val canvas = page.canvas

        val title = paint(20f, true)
        val body = paint(11f)
        val bold = paint(11f, true)
        val small = paint(9f)
        val rule = Paint().apply {
            color = AColor.parseColor("#CCCCCC")
            strokeWidth = 0.8f
        }

        val (navy, gold) = themeColors()
        canvas.drawRect(0f, 0f, PAGE_W.toFloat(), 14f, Paint().apply { color = navy })
        canvas.drawRect(0f, 14f, PAGE_W.toFloat(), 16.5f, Paint().apply { color = gold })
        title.typeface = Typeface.create(Typeface.SERIF, Typeface.BOLD)
        title.color = navy
        rule.color = gold
        var y = MARGIN + 14f
        canvas.drawText(shopName, MARGIN, y, title)
        y += 18f
        if (shopAddress.isNotBlank()) {
            canvas.drawText(shopAddress, MARGIN, y, small)
            y += 12f
        }
        if (shopPhone.isNotBlank()) {
            canvas.drawText("Phone: $shopPhone", MARGIN, y, small)
            y += 12f
        }
        if (shopGstin.isNotBlank()) {
            canvas.drawText("GSTIN: $shopGstin", MARGIN, y, small)
            y += 12f
        }
        upiLine()?.let {
            canvas.drawText("UPI: " + it.removePrefix("UPI "), MARGIN, y, small)
            y += 12f
        }

        canvas.drawText("TAX INVOICE", PAGE_W - MARGIN - 90f, MARGIN + 12f, bold)
        canvas.drawText(inv.number, PAGE_W - MARGIN - 90f, MARGIN + 28f, body)

        y += 10f
        line(canvas, y, rule)
        y += 20f
        canvas.drawText("Bill To:", MARGIN, y, bold)
        y += 15f
        canvas.drawText(inv.partyName.ifBlank { "Cash Customer" }, MARGIN, y, body)
        y += 14f
        if (inv.phone.isNotBlank()) {
            canvas.drawText(inv.phone, MARGIN, y, body)
            y += 14f
        }
        canvas.drawText("Date: ${fmtDate(inv.date)}", PAGE_W - MARGIN - 130f, y - 29f, body)

        y += 10f
        line(canvas, y, rule)
        y += 16f
        canvas.drawText("#", MARGIN, y, bold)
        canvas.drawText("Item", MARGIN + 25f, y, bold)
        canvas.drawText("Qty", MARGIN + 250f, y, bold)
        canvas.drawText("Rate", MARGIN + 320f, y, bold)
        canvas.drawText("Amount", MARGIN + 410f, y, bold)
        y += 6f
        line(canvas, y, rule)
        y += 16f

        inv.lines.forEachIndexed { i, l ->
            canvas.drawText((i + 1).toString(), MARGIN, y, body)
            canvas.drawText(l.name.take(32), MARGIN + 25f, y, body)
            canvas.drawText(money(l.qty), MARGIN + 250f, y, body)
            canvas.drawText(money(l.rate), MARGIN + 320f, y, body)
            canvas.drawText(money(l.qty * l.rate), MARGIN + 410f, y, body)
            y += 16f
        }

        y += 4f
        line(canvas, y, rule)
        y += 20f

        fun row(label: String, value: String, isBold: Boolean = false) {
            val p = if (isBold) bold else body
            canvas.drawText(label, MARGIN + 300f, y, p)
            canvas.drawText(value, MARGIN + 410f, y, p)
            y += 16f
        }

        row("Subtotal", money(inv.subtotal))
        if (inv.discount > 0) row("Discount", "-" + money(inv.discount))
        if (inv.gstPercent > 0) row("GST (${money(inv.gstPercent)}%)", money(inv.gstAmount))
        y += 4f
        line(canvas, y, rule)
        y += 20f
        row("TOTAL", "Rs " + money(inv.total), true)

        y += 20f
        canvas.drawText(if (inv.paid) "PAID" else "UNPAID", MARGIN, y, bold)
        y += 30f
        canvas.drawText(footerLine(), MARGIN, y, small)
        val terms = com.bahikhata.app.data.Repo.setting("terms", "").trim()
        if (com.bahikhata.app.data.Repo.setting("terms_on", "1") == "1" && terms.isNotEmpty() && y < PAGE_H - 160f) {
            y += 26f
            canvas.drawText("TERMS & RULES", MARGIN, y, Paint(bold).apply { color = gold })
            y += 14f
            val tp = Paint(small).apply { color = AColor.parseColor("#555555") }
            terms.lines().forEach { para ->
                var cur = ""
                para.split(" ").forEach { w ->
                    val t = if (cur.isEmpty()) w else "$cur $w"
                    if (tp.measureText(t) > PAGE_W - 2 * MARGIN) { if (y < PAGE_H - 90f) canvas.drawText(cur, MARGIN, y, tp); y += 12f; cur = w } else cur = t
                }
                if (y < PAGE_H - 90f) canvas.drawText(cur, MARGIN, y, tp); y += 12f
            }
        }
        val sy = PAGE_H - 70f
        canvas.drawLine(PAGE_W - MARGIN - 170f, sy, PAGE_W - MARGIN, sy, Paint().apply { color = navy; strokeWidth = 0.8f })
        canvas.drawText(signatoryLabel(), PAGE_W - MARGIN - 140f, sy + 13f, small)

        doc.finishPage(page)
        val file = File(ctx.cacheDir, "invoice_${inv.number}_${System.currentTimeMillis()}.pdf")
        FileOutputStream(file).use { doc.writeTo(it) }
        doc.close()
        return file
    }
}
